<#
  Build PharmacySync.exe using the C# compiler that ships with .NET Framework 4.x (no SDK needed).

  Usage:
    powershell -ExecutionPolicy Bypass -File build.ps1 -AdminUser admin -AdminPassword "YourStrongPassword"

  The login username/password are baked into the exe as a salted PBKDF2 hash (the password itself is not stored).
  If you omit them, the previously generated credentials (src\Credentials.Generated.cs) are reused.

  -NoAdmin  : build without the "Run as administrator" manifest (developer testing only).
  -Target   : All (default) | Modern | Win7
              Modern -> dist\PharmacySync.exe       (Windows 10 / 11, .NET 4.x)
              Win7   -> dist\PharmacySync-Win7.exe  (Windows 7, .NET 3.5 - nothing to install on the client)
#>
param(
    [string]$AdminUser,
    [string]$AdminPassword,
    [switch]$NoAdmin,
    [string]$Output,
    [ValidateSet("All", "Modern", "Win7")]
    [string]$Target = "All"
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Definition
$Src = Join-Path $Root "src"
$BuildDir = Join-Path $Root "build"
$Dist = Join-Path $Root "dist"
if (-not $Output) { $Output = Join-Path $Dist "PharmacySync.exe" }
$OutputWin7 = Join-Path (Split-Path $Output -Parent) ([IO.Path]::GetFileNameWithoutExtension($Output) + "-Win7.exe")
New-Item -ItemType Directory -Force -Path $BuildDir, (Split-Path $Output -Parent) | Out-Null

$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR "Microsoft.NET\Framework\v4.0.30319\csc.exe" }
if (-not (Test-Path $csc)) { throw ".NET Framework 4.x compiler not found." }

# ---------------- credentials ----------------
$CredFile = Join-Path $Src "Credentials.Generated.cs"
if ($AdminUser -and $AdminPassword) {
    $salt = New-Object byte[] 16
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($salt)
    $iter = 100000
    $kdf = New-Object Security.Cryptography.Rfc2898DeriveBytes($AdminPassword, $salt, $iter)
    $hash = $kdf.GetBytes(32)
    $u = $AdminUser.Replace('\', '\\').Replace('"', '\"')
    @"
// AUTO-GENERATED by build.ps1 - do not edit by hand.
namespace PharmacySync
{
    internal static class Credentials
    {
        public const string Username = "$u";
        public const string Salt = "$([Convert]::ToBase64String($salt))";
        public const string Hash = "$([Convert]::ToBase64String($hash))";
        public const int Iterations = $iter;
    }
}
"@ | Set-Content -Path $CredFile -Encoding UTF8
    Write-Host "Credentials generated for user '$AdminUser'."
} elseif (-not (Test-Path $CredFile)) {
    throw "First build: pass -AdminUser and -AdminPassword."
}

# ---------------- icon ----------------
Add-Type -AssemblyName System.Drawing
$IconFile = Join-Path $BuildDir "app.ico"
function New-IconPng([int]$size) {
    $bmp = New-Object Drawing.Bitmap $size, $size
    $g = [Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $g.Clear([Drawing.Color]::Transparent)
    $r = [Math]::Max(2, [int]($size / 5)); $d = $r * 2; $s = $size - 1
    $path = New-Object Drawing.Drawing2D.GraphicsPath
    $path.AddArc(0, 0, $d, $d, 180, 90); $path.AddArc($s - $d, 0, $d, $d, 270, 90)
    $path.AddArc($s - $d, $s - $d, $d, $d, 0, 90); $path.AddArc(0, $s - $d, $d, $d, 90, 90); $path.CloseFigure()
    $rect = New-Object Drawing.Rectangle 0, 0, $size, $size
    $brush = New-Object Drawing.Drawing2D.LinearGradientBrush $rect, ([Drawing.Color]::FromArgb(13, 118, 110)), ([Drawing.Color]::FromArgb(17, 78, 74)), 45.0
    $g.FillPath($brush, $path)
    $u = $size / 16.0
    $w = [Drawing.Brushes]::White
    $g.FillRectangle($w, [single](6.5 * $u), [single](3.5 * $u), [single](3 * $u), [single](9 * $u))
    $g.FillRectangle($w, [single](3.5 * $u), [single](6.5 * $u), [single](9 * $u), [single](3 * $u))
    $g.Dispose()
    $ms = New-Object IO.MemoryStream
    $bmp.Save($ms, [Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    return ,$ms.ToArray()
}
$sizes = 16, 24, 32, 48, 64, 128, 256
$images = @(); foreach ($sz in $sizes) { $images += ,(New-IconPng $sz) }
$fs = [IO.File]::Create($IconFile)
$bw = New-Object IO.BinaryWriter $fs
$bw.Write([UInt16]0); $bw.Write([UInt16]1); $bw.Write([UInt16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $sz = $sizes[$i]; $len = $images[$i].Length
    $bw.Write([byte]($(if ($sz -ge 256) { 0 } else { $sz }))); $bw.Write([byte]($(if ($sz -ge 256) { 0 } else { $sz })))
    $bw.Write([byte]0); $bw.Write([byte]0); $bw.Write([UInt16]1); $bw.Write([UInt16]32)
    $bw.Write([UInt32]$len); $bw.Write([UInt32]$offset); $offset += $len
}
foreach ($img in $images) { $bw.Write($img) }
$bw.Close()

