# ---------------- app.config (run on any .NET 4.x runtime) ----------------
# (single-file exe: no config needed; the v4 runtime is selected automatically)

# ---------------- compile ----------------
$files = Get-ChildItem -Path $Src -Recurse -Filter *.cs | ForEach-Object { $_.FullName }
$common = @("/nologo", "/target:winexe", "/platform:anycpu", "/optimize+", "/codepage:65001", "/utf8output",
            "/win32icon:$IconFile", "/win32manifest:$ManifestFile")

# 1) Windows 10 / 11  -> .NET Framework 4.x (built into Windows 10/11)
if ($Target -ne "Win7") {
    $refs = "System.dll", "System.Core.dll", "System.Data.dll", "System.Drawing.dll", "System.Windows.Forms.dll",
            "System.Security.dll", "System.Web.Extensions.dll", "Microsoft.CSharp.dll", "System.Xml.dll"
    $cscArgs = $common + @("/out:$Output")
    $cscArgs += $refs | ForEach-Object { "/reference:$_" }
    $cscArgs += $files
    & $csc @cscArgs
    if ($LASTEXITCODE -ne 0) { throw "Build failed (Windows 10/11)." }
    Write-Host "Built (Windows 10/11, .NET 4.x): $Output" -ForegroundColor Green
}

# 2) Windows 7 -> .NET 3.5 (built into every Windows 7, even without Service Pack).
#    HTTPS uses the embedded BouncyCastle TLS 1.2 stack + bundled root certificates (src\Win7\).
if ($Target -ne "Modern") {
    $V2 = Join-Path $env:WINDIR "Microsoft.NET\Framework\v2.0.50727"
    $V35 = Join-Path ${env:ProgramFiles(x86)} "Reference Assemblies\Microsoft\Framework\v3.5"
    if (-not (Test-Path (Join-Path $V2 "mscorlib.dll")) -or -not (Test-Path (Join-Path $V35 "System.Core.dll"))) {
        throw "Windows 7 build needs .NET Framework 3.5 on this PC (Windows Features -> .NET Framework 3.5)."
    }
    $bc = Join-Path $Root "lib\BouncyCastle.Crypto.dll"
    $pem = Join-Path $Src "Win7\roots.pem"
    $refs = (Join-Path $V2 "mscorlib.dll"), (Join-Path $V2 "System.dll"), (Join-Path $V2 "System.Data.dll"),
            (Join-Path $V2 "System.Drawing.dll"), (Join-Path $V2 "System.Windows.Forms.dll"), (Join-Path $V2 "System.Security.dll"),
            (Join-Path $V2 "System.XML.dll"), (Join-Path $V35 "System.Core.dll"), (Join-Path $V35 "System.Web.Extensions.dll"), $bc
    $cscArgs = $common + @("/noconfig", "/nostdlib+", "/define:NET35", "/out:$OutputWin7",
                           "/resource:$bc,PharmacySync.BouncyCastle.Crypto.dll", "/resource:$pem,PharmacySync.roots.pem")
    $cscArgs += $refs | ForEach-Object { "/reference:$_" }
    $cscArgs += $files
    & $csc @cscArgs
    if ($LASTEXITCODE -ne 0) { throw "Build failed (Windows 7)." }
    Write-Host "Built (Windows 7, .NET 3.5):        $OutputWin7" -ForegroundColor Green
}
